from __future__ import annotations

import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

from .config import Settings
from .domain import MRICase, TISSUE_NAMES, TissueName, tissue_key


def _safe_case_segment(value: str) -> str:
    """Keep filesystem path segments simple and prevent accidental nesting."""
    return value.replace("/", "_").replace("\\", "_").strip()


def _case_dir(root: Path, case: MRICase) -> Path:
    """Return the standard subject/acquisition directory for one stage root."""
    return (
        Path(root)
        / _safe_case_segment(case.subject_id)
        / _safe_case_segment(case.acquisition_date)
    )


def _remove_tree(path: Path) -> bool:
    """Remove a directory tree if it exists. Return True when something was removed."""
    if not path.exists():
        return False
    if not path.is_dir():
        raise ValueError(f"Expected directory path, got file path: {path}")
    shutil.rmtree(path)
    return True

def _move_tree(source: Path, target: Path, *, overwrite: bool = False) -> bool:
    """
    Move a directory tree if it exists.

    Returns True when a directory was moved.
    Raises if the target already exists and overwrite=False.
    """
    if not source.exists():
        return False

    if not source.is_dir():
        raise ValueError(f"Expected source directory, got file path: {source}")

    if target.exists():
        if not overwrite:
            raise FileExistsError(
                f"Cannot rename workspace directory because target already exists:\n"
                f"source: {source}\n"
                f"target: {target}"
            )

        if not target.is_dir():
            raise ValueError(f"Expected target directory, got file path: {target}")

        shutil.rmtree(target)

    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(source), str(target))
    return True


def _remove_file(path: Path) -> bool:
    """Remove one file if it exists. Return True when something was removed."""
    if not path.exists():
        return False
    if not path.is_file():
        raise ValueError(f"Expected file path, got non-file path: {path}")
    path.unlink()
    return True


def _prune_empty_parent(path: Path) -> None:
    """
    Remove the direct parent folder when it became empty.

    For a case directory like processed_mri/fast/<subject>/<date>, this removes
    <subject> if there are no more acquisition folders under it. It deliberately
    stops there and never tries to remove the configured stage root.
    """
    parent = path.parent
    try:
        parent.rmdir()
    except OSError:
        return


@dataclass(frozen=True)
class CaseWorkspace:
    """
    Filesystem workspace for one MRI acquisition.

    A case is identified by (subject_id, acquisition_date). This class owns the
    concrete local file layout used by the application:

        input_mri/<subject>/<date>/...
        processed_mri/reoriented/<subject>/<date>/...
        processed_mri/hd_bet/<subject>/<date>/...
        processed_mri/fast/<subject>/<date>/...
        processed_mri/meshes/<subject>/<date>/...

    CaseWorkspace intentionally handles both creation and deletion of those
    local folders. The database/API layer can use it after metadata CRUD succeeds.
    """

    subject_id: str
    acquisition_date: str
    source_raw_path: Path
    raw_path: Path

    input_mri_dir: Path
    reoriented_dir: Path
    hd_bet_dir: Path
    fast_dir: Path
    mesh_dir: Path

    @property
    def case_id(self) -> str:
        return f"{self.subject_id}_{self.acquisition_date}"

    # ------------------------------------------------------------------
    # directories
    # ------------------------------------------------------------------

    @property
    def processed_stage_dirs(self) -> list[Path]:
        """Directories generated by the processing pipeline."""
        return [
            self.reoriented_dir,
            self.hd_bet_dir,
            self.fast_dir,
            self.mesh_dir,
        ]

    @property
    def stage_dirs(self) -> list[Path]:
        """All local directories owned by this case, including the staged input."""
        return [self.input_mri_dir, *self.processed_stage_dirs]

    @property
    def existing_stage_dirs(self) -> list[Path]:
        return [directory for directory in self.stage_dirs if directory.exists()]

    @property
    def workspace_exists(self) -> bool:
        return any(directory.exists() for directory in self.stage_dirs)

    def ensure_directories(self) -> None:
        """Create all local workspace directories for this acquisition."""
        for directory in self.stage_dirs:
            directory.mkdir(parents=True, exist_ok=True)

    def ensure_input_file(self, *, overwrite: bool = False) -> None:
        """
        Copy the caller-selected raw MRI into the standardized input folder.

        If source_raw_path already points to raw_path, no copy is needed.
        Existing canonical input is preserved unless overwrite=True.
        """
        self.input_mri_dir.mkdir(parents=True, exist_ok=True)

        source = Path(self.source_raw_path).resolve()
        target = Path(self.raw_path).resolve()

        if source == target:
            return

        if not source.exists():
            raise FileNotFoundError(f"Raw MRI source file does not exist: {source}")
        if not source.is_file():
            raise ValueError(f"Raw MRI source path is not a file: {source}")

        if target.exists() and not overwrite:
            return

        shutil.copy2(source, target)

    # ------------------------------------------------------------------
    # deletion / cleanup
    # ------------------------------------------------------------------

    def delete_workspace(
        self,
        *,
        include_input: bool = True,
        prune_empty_subject_dirs: bool = True,
    ) -> list[Path]:
        """
        Delete this case's local filesystem workspace.

        include_input=True removes input_mri/<subject>/<date>/ as well as all
        processed outputs. Use include_input=False when you only want to clear
        generated outputs and keep the staged raw MRI.

        Returns the case directories that were actually removed.
        """
        directories = self.stage_dirs if include_input else self.processed_stage_dirs
        removed: list[Path] = []

        for directory in directories:
            if _remove_tree(directory):
                removed.append(directory)
                if prune_empty_subject_dirs:
                    _prune_empty_parent(directory)

        return removed

    def delete_processed_outputs(self, *, prune_empty_subject_dirs: bool = True) -> list[Path]:
        """Delete all generated processing outputs while keeping the staged input MRI."""
        return self.delete_workspace(
            include_input=False,
            prune_empty_subject_dirs=prune_empty_subject_dirs,
        )

    def delete_input(self, *, prune_empty_subject_dirs: bool = True) -> list[Path]:
        """Delete only input_mri/<subject>/<date>/ for this case."""
        removed: list[Path] = []
        if _remove_tree(self.input_mri_dir):
            removed.append(self.input_mri_dir)
            if prune_empty_subject_dirs:
                _prune_empty_parent(self.input_mri_dir)
        return removed

    def delete_files(self, paths: Iterable[Path]) -> list[Path]:
        """Delete existing files from the provided path collection."""
        removed: list[Path] = []
        for path in paths:
            if _remove_file(Path(path)):
                removed.append(Path(path))
        return removed

    def delete_reorientation_outputs(self) -> list[Path]:
        return self.delete_files([self.reoriented_path])

    def delete_hd_bet_outputs(self) -> list[Path]:
        return self.delete_files([
            self.skull_stripped_path,
            self.skull_stripped_mask_path,
        ])

    def delete_fast_outputs(self) -> list[Path]:
        """
        Delete known FAST PVE outputs for this case.

        This intentionally removes the explicit expected FAST PVE files, not every
        random file in fast_dir. That keeps accidental extra logs/debug files safe.
        """
        return self.delete_files(self.fast_pve_paths.values())

    def delete_mesh_analysis_outputs(self) -> list[Path]:
        return self.delete_files(self.mesh_analysis_output_paths)
    
    # ------------------------------------------------------------------
    # rename
    # ------------------------------------------------------------------

    def rename_to(
        self,
        target_workspace: "CaseWorkspace",
        *,
        overwrite: bool = False,
        prune_empty_subject_dirs: bool = True,
    ) -> list[tuple[Path, Path]]:
        """
        Rename/move this case workspace to another acquisition date.

        This is meant for correcting acquisition_date mistakes, for example:

            input_mri/<subject>/2026-05-17
                -> input_mri/<subject>/2026-05-18

            processed_mri/fast/<subject>/2026-05-17
                -> processed_mri/fast/<subject>/2026-05-18

        The method moves every existing stage directory. Missing stage directories
        are ignored, because a case may exist in the DB before all processing stages
        have generated files.

        Returns a list of (old_path, new_path) pairs that were actually moved.
        """
        if self.subject_id != target_workspace.subject_id:
            raise ValueError(
                "CaseWorkspace.rename_to only supports acquisition-date rename for "
                "the same subject. Subject rename should be a separate operation."
            )

        if self.acquisition_date == target_workspace.acquisition_date:
            return []

        source_dirs = self.stage_dirs
        target_dirs = target_workspace.stage_dirs

        moved: list[tuple[Path, Path]] = []

        for source_dir, target_dir in zip(source_dirs, target_dirs, strict=True):
            if _move_tree(source_dir, target_dir, overwrite=overwrite):
                moved.append((source_dir, target_dir))

                if prune_empty_subject_dirs:
                    _prune_empty_parent(source_dir)

        return moved

    # ------------------------------------------------------------------
    # reorientation
    # ------------------------------------------------------------------

    @property
    def reoriented_path(self) -> Path:
        return self.reoriented_dir / f"{self.subject_id}_reo.nii.gz"

    @property
    def has_reoriented(self) -> bool:
        return self.reoriented_path.exists()

    # ------------------------------------------------------------------
    # HD-BET
    # ------------------------------------------------------------------

    @property
    def skull_stripped_path(self) -> Path:
        return self.hd_bet_dir / f"{self.subject_id}_bet.nii.gz"

    @property
    def skull_stripped_mask_path(self) -> Path:
        return self.hd_bet_dir / f"{self.subject_id}_bet_mask.nii.gz"

    @property
    def hd_bet_output_paths(self) -> list[Path]:
        return [self.skull_stripped_path, self.skull_stripped_mask_path]

    # ------------------------------------------------------------------
    # FAST
    # ------------------------------------------------------------------

    @property
    def fast_input_path(self) -> Path:
        return self.skull_stripped_path

    @property
    def fast_prefix(self) -> Path:
        """
        FAST receives a prefix and generates several files from it.
        Example: <prefix>_pve_0.nii.gz
        """
        return self.fast_dir / self.subject_id

    @property
    def fast_pve_csf_path(self) -> Path:
        return self.fast_dir / f"{self.subject_id}_pve_0.nii.gz"

    @property
    def fast_pve_gm_path(self) -> Path:
        return self.fast_dir / f"{self.subject_id}_pve_1.nii.gz"

    @property
    def fast_pve_wm_path(self) -> Path:
        return self.fast_dir / f"{self.subject_id}_pve_2.nii.gz"

    @property
    def fast_pve_paths(self) -> dict[str, Path]:
        return {
            TissueName.CSF.value: self.fast_pve_csf_path,
            TissueName.GM.value: self.fast_pve_gm_path,
            TissueName.WM.value: self.fast_pve_wm_path,
        }

    @property
    def has_fast_pve_outputs(self) -> bool:
        return all(path.exists() for path in self.fast_pve_paths.values())

    @property
    def missing_fast_pve_paths(self) -> list[Path]:
        return [path for path in self.fast_pve_paths.values() if not path.exists()]

    # ------------------------------------------------------------------
    # meshes / metrics
    # ------------------------------------------------------------------

    def mesh_path_for(self, tissue: TissueName | str) -> Path:
        key = tissue_key(tissue)
        return self.mesh_dir / f"{self.subject_id}_{key}_mesh.glb"


    @property
    def mesh_csf_mesh_path(self) -> Path:
        return self.mesh_path_for(TissueName.CSF)

    @property
    def mesh_gm_mesh_path(self) -> Path:
        return self.mesh_path_for(TissueName.GM)

    @property
    def mesh_wm_mesh_path(self) -> Path:
        return self.mesh_path_for(TissueName.WM)


    @property
    def mesh_metrics_json_path(self) -> Path:
        return self.mesh_dir / f"{self.subject_id}_metrics.json"

    # Preferred shorter name for new code.
    @property
    def metrics_json_path(self) -> Path:
        return self.mesh_metrics_json_path

    @property
    def mesh_paths(self) -> dict[str, Path]:
        return {tissue.value: self.mesh_path_for(tissue) for tissue in TISSUE_NAMES}


    @property
    def mesh_output_paths(self) -> list[Path]:
        return [*self.mesh_paths.values(), self.mesh_metrics_json_path]


    @property
    def mesh_analysis_output_paths(self) -> list[Path]:
        return [
            *self.mesh_paths.values(),
            self.mesh_metrics_json_path,
        ]

    @property
    def has_complete_mesh_outputs(self) -> bool:
        return all(path.exists() for path in self.mesh_output_paths)

    @property
    def has_any_mesh_outputs(self) -> bool:
        return any(path.exists() for path in self.mesh_output_paths)


    @property
    def has_complete_mesh_analysis_outputs(self) -> bool:
        return all(path.exists() for path in self.mesh_analysis_output_paths)

    @property
    def has_any_mesh_analysis_outputs(self) -> bool:
        return any(path.exists() for path in self.mesh_analysis_output_paths)

    def existing_paths(self, paths: Iterable[Path]) -> list[Path]:
        return [path for path in paths if path.exists()]


class FileSystemWorkspaceProvider:
    """
    Small convenience factory for CaseWorkspace.

    It is not meant as a long-term storage abstraction. It simply keeps creation
    and deletion calls short for CLI/API code while CaseWorkspace owns the real
    filesystem behavior.
    """

    def __init__(self, settings: Settings, *, create_directories: bool = True):
        self.settings = settings
        self.create_directories = create_directories

    def build_workspace(self, case: MRICase) -> CaseWorkspace:
        return build_case_workspace(case, self.settings)

    # Backwards-compatible alias for existing preprocessing code.
    def create_workspace(self, case: MRICase) -> CaseWorkspace:
        workspace = self.build_workspace(case)

        if self.create_directories:
            workspace.ensure_directories()
            workspace.ensure_input_file(overwrite=self.settings.overwrite)

        return workspace

    def get_workspace(self, case: MRICase) -> CaseWorkspace:
        """Build paths for a case without creating folders or copying the input file."""
        return self.build_workspace(case)
    
    def rename_workspace(
        self,
        old_case: MRICase,
        new_case: MRICase,
        *,
        overwrite: bool = False,
        prune_empty_subject_dirs: bool = True,
    ) -> list[tuple[Path, Path]]:
        old_workspace = self.build_workspace(old_case)
        new_workspace = self.build_workspace(new_case)

        return old_workspace.rename_to(
            new_workspace,
            overwrite=overwrite,
            prune_empty_subject_dirs=prune_empty_subject_dirs,
        )

    def delete_workspace(
        self,
        case: MRICase,
        *,
        include_input: bool = True,
        prune_empty_subject_dirs: bool = True,
    ) -> list[Path]:
        workspace = self.build_workspace(case)
        return workspace.delete_workspace(
            include_input=include_input,
            prune_empty_subject_dirs=prune_empty_subject_dirs,
        )


def build_case_workspace(case: MRICase, settings: Settings) -> CaseWorkspace:
    """
    Build the local workspace paths for one subject/date acquisition without
    creating directories.
    """
    input_mri_dir = _case_dir(Path(settings.input_mri_dir), case)

    return CaseWorkspace(
        subject_id=case.subject_id,
        acquisition_date=case.acquisition_date,
        source_raw_path=case.raw_path,
        raw_path=input_mri_dir / Path(case.raw_path).name,
        input_mri_dir=input_mri_dir,
        reoriented_dir=_case_dir(Path(settings.reoriented_dir), case),
        hd_bet_dir=_case_dir(Path(settings.hd_bet_dir), case),
        fast_dir=_case_dir(Path(settings.fast_dir), case),
        mesh_dir=_case_dir(Path(settings.mesh_dir), case),
    )


